/**
 * 掌纹二值化的阈值系数，单独成一个模块。
 *
 * 为什么不放在 worker 里：worker 文件一被 import 就会注册 self.onmessage，
 * 在 node 的测试环境里直接报错。判线要能被测试引用，就得住在这儿。
 */

/**
 * 二值化的阈值系数：前景 = 响应 > 局部均值 + k × 局部标准差。
 *
 * ── 这个数原先是 0.35，而 0.35 是错的 ────────────────────────
 * 合成掌图上实测（三条已知位置的纹路，纹宽 3px）：
 *
 *   k      前景占比   折线数  最长/掌宽   画在真纹上的比例
 *   0.35     32.2%     24      2.42            8%
 *   1.20     10.8%     24      2.07           36%
 *   1.60      5.3%      3      1.54          100%
 *   2.00      2.2%      4      1.34          100%
 *
 * k=0.35 把**三分之一的画面**判成了纹路。细化那样一片区域，得到的是一张
 * 蔓延全掌的网，于是追踪出 24 条折线、最长的有 2.42 个掌宽（比任何真掌纹
 * 都长），而其中**只有 8% 的长度真的落在纹路上**。用户看到的满掌乱线就是它。
 *
 * ── 现在这个数怎么来的 ──────────────────────────────────────
 * 从「掌面有多大比例真的是纹」反推：三条主纹加若干细纹，约八条，
 * 每条长约 250px、宽约 3px，合计约 6000px，占 512² 的 2.3%。
 * 而对近高斯的响应分布，均值 + 2σ 恰好选出约 2.3%。两头对得上。
 * 实测也印证：k=2.0 时覆盖率 99–100%，且画出来的线 100% 落在真纹上。
 *
 * ⚠️ CALIBRATE：合成图只有三条纹，真实掌面的细纹更多，分布也未必是高斯。
 * 判线应在真实样本到手后按分位重设 —— dev/validate.ts 的手相定标台正为此准备。
 * 实测 k=1.6 同样是 100% 的准确率，因此这不是一条卡在刀刃上的判线。
 */
export const PALMLINE_THRESHOLD_K = 2.0
