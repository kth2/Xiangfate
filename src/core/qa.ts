/**
 * 从问题文本判定主题。返回值按 TOPIC_ORDER 排序，可能为空。
 *
 * 只做关键词匹配 —— 判错主题的代价是给模型一条不相干的提示，
 * 而模型仍然只能基于特征数据立论，所以这里不需要更聪明的做法。
 */
export function detectTopics(question: string): QaTopic[] {
  const q = question.trim()
  if (!q) return []
  return TOPIC_ORDER.filter((t) => TOPIC_GUIDES[t].keywords.some((k) => q.includes(k)))
}

