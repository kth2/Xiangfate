export type QaTopic =
  | 'overall'
  | 'wealth'
  | 'career'
  | 'relationship'
  | 'health'
  | 'children'
  | 'timing'
  | 'personality'

export interface TopicGuide {
  /** 主题名，用于 prompt 里点题 */
  label: string
  /** 传统术士的应对方向（知识库第 0 节） */
  approach: string
  /**
   * 本项目口径。仅在传统做法与内容策略冲突时才有 ——
   * 有 boundary 的主题，注入 prompt 时 boundary 必须一起给。
   */
  boundary?: string
  /** 命中即判定为该主题。宁可漏判，不可宽判：漏判只是少一条提示，宽判会给错方向 */
  keywords: string[]
}

